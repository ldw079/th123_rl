# -*- coding: utf-8 -*-
"""R49(L1执行补件): 帧级反应宏+缺失技法宏 — 由frame_events反应表消费。

三类新增(技法覆盖分析的执行缺口):
1. **DD变体** — 结界2/4已有, 补: 6DD(前结界/前冲取消), 1DD(后结界),
   空DD(空中结界), 3DD(下前结界)
2. **投技** — A+D同按(全角色通用指令), 近距专用
3. **放帧变体** — 同招±N帧延迟(攻略"压制中的灵魂"):
   快速版(减2帧)/标准/慢速版(加3帧)/延迟版(加6帧)
   用于打乱对手防御节奏(拍子择)

这些宏由帧级事件系统自动选择(不进普通策略的动作空间——
避免策略层学习负担, 由规则库条件化触发)。
也可追加到宏库末尾供策略层学习(末位追加契约)。
"""
from __future__ import annotations

# ---- DD变体(结界系, 全角色通用) ----
DD_MACROS = [
    # 6DD: 前方向+D双按 — 前冲结界(脱压+前进)
    ("DD·前",  [(("right", "D"), 2), (("right", "D"), 6)]),
    # 1DD: 后方向+D双按 — 后撤结界(拉开距离)
    ("DD·后",  [(("left", "D"), 2), (("left", "D"), 6)]),
    # 2DD已有(结界2), 4DD已有(结界4)
    # 空中DD: 空中任意方向+D — 空中结界(空防不能择的对策)
    ("DD·空",  [(("up", "D"), 2), (("up", "D"), 6)]),
    # 3DD: 斜下+D — 蹲姿结界(下段逃压)
    ("DD·蹲",  [(("down", "right", "D"), 2), (("down", "right", "D"), 6)]),
]

# ---- 投技(全角色通用: 近距A+D同按) ----
THROW_MACROS = [
    ("投技",   [(("A", "D"), 4)]),      # 近距投掷(10F无敌,拆投10F窗)
    ("投技·空", [(("up",), 4), (("A", "D"), 4)]),  # 空中投(打逆对策)
]

# ---- 放帧变体(拍子择 — 压制灵魂) ----
# 以5A为例: 同一招在不同延迟后出 — 打乱对手防御节奏
STAGGER_MACROS = [
    ("放帧·快",  [(("A",), 2)]),           # 最短(抢节奏)
    ("放帧·标准", [((), 3), (("A",), 4)]),  # 标准(3帧延迟)
    ("放帧·慢",  [((), 6), (("A",), 4)]),  # 慢3帧(打乱)
    ("放帧·迟",  [((), 9), (("A",), 4)]),  # 迟6帧(骗凹)
    # 2A版
    ("放帧·下快", [(("down",), 2), (("down", "A"), 2)]),
    ("放帧·下慢", [(("down",), 3), ((), 4), (("down", "A"), 4)]),
]

# ---- 表里择成对宏(打逆) ----
MIXUP_MACROS = [
    # 6D8→2D: 表里下地择(前dash上→蹲, 混淆表里)
    ("择·表里下地", [(("right", "D"), 3), (("up",), 4),
                     (("down",), 2), (("down",), 4)]),
    # 假动作→JA: 前dash看起来要前攻→跳A打逆
    ("择·假动JA",  [(("right", "D"), 4), ((), 2),
                    (("up",), 4), (("A",), 8)]),
    # 44→J2A: 后dash→空中下A(纯打逆压起身)
    ("择·后逆",   [(("left",), 3), ((), 1), (("left",), 4),
                   (("up",), 4), (("down",), 2), (("down", "A"), 10)]),
]

def get_all_frame_macros():
    """返回全部帧级宏(可追加到宏库末尾)。"""
    return (DD_MACROS + THROW_MACROS + STAGGER_MACROS + MIXUP_MACROS)
